#!/usr/bin/env node
/**
 * fork-rename-scope.mjs — retarget this fork's npm scope, repo links, and author
 * metadata in one auditable, re-runnable pass.
 *
 * Why a script instead of a one-off sed: the correct scope is whatever your npm
 * account or org owns (`npm whoami`), and getting that wrong means redoing the
 * whole rename. This is parameterized and idempotent, so re-targeting costs one
 * command: `node scripts/fork-rename-scope.mjs @<real-account>`.
 *
 * Usage:
 *   node scripts/fork-rename-scope.mjs @hs1n [--repo hs1n/pi-monocoque] [--dry-run]
 *   node scripts/fork-rename-scope.mjs --report          # show what it would touch
 *
 * Scope of the rewrite — "does this text describe THIS repo's packages?":
 *
 *   REWRITTEN
 *     packages/**            package.json names/deps/peers + sources + tests + READMEs
 *     test/**, scripts/**    repo-wide setup and tooling
 *     docs/**                the repo's own conventions
 *     .rpiv/guidance/packages/**   per-package architecture notes for agents
 *
 *   DELIBERATELY NOT REWRITTEN (they describe upstream, not us)
 *     README.md, FORK_NOTICE.md, INSTALL-FORK.md, .rpiv/guidance/architecture.md
 *                            upstream's marketing/identity prose lives here, mixed
 *                            with our fork banner — a partial rewrite would produce a
 *                            document that claims our scope while linking their X
 *                            handle and domain
 *     packages/rpiv-site/**  upstream's marketing site (not deployed by this fork),
 *                            and its guidance notes under .rpiv/guidance/
 *     package-lock.json      regenerated by `npm install` after the rename
 *     per-package CHANGELOG.md       historical release records
 *     any __fixtures__ subtree       recorded pipeline runs, cited verbatim by tests
 *
 * Node built-ins only — matches the scripts/ convention in
 * .rpiv/guidance/scripts/architecture.md.
 */

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const REPO_ROOT = resolve(import.meta.dirname, "..");

/** Directories whose contents are rewritten. */
const RENAME_ROOTS = ["packages", "test", "scripts", "docs", ".rpiv/guidance/packages"];
/** Path prefixes (repo-relative, POSIX) never rewritten. */
const SKIP_PREFIXES = ["node_modules/"];
/** Basenames never rewritten, anywhere. */
const SKIP_BASENAMES = new Set(["CHANGELOG.md"]);
/** Path segments that mark a subtree as a record rather than a source of truth. */
const SKIP_SEGMENTS = new Set(["__fixtures__", "node_modules", ".git"]);
/** Text extensions worth reading. Anything else is assumed binary. */
const TEXT_EXT = /\.(ts|tsx|mts|cts|js|mjs|cjs|json|md|sh|bash|yml|yaml|astro|css|txt)$/;

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const reportOnly = args.includes("--report");
const noMetadata = args.includes("--no-metadata");
const positional = args.filter((a) => !a.startsWith("--"));
const repoFlagIndex = args.indexOf("--repo");
const repoArg = repoFlagIndex >= 0 ? args[repoFlagIndex + 1] : undefined;

const PKG_DIRS = readdirSync(join(REPO_ROOT, "packages")).filter((d) =>
	statSync(join(REPO_ROOT, "packages", d)).isDirectory(),
);
const PKG_GLOBS = PKG_DIRS;

/** Current scope, detected from the workspace package names. */
function detectScope() {
	const scopes = new Set();
	for (const dir of PKG_GLOBS) {
		const p = join(REPO_ROOT, "packages", dir, "package.json");
		if (!existsSync(p)) continue;
		const { name } = JSON.parse(readFileSync(p, "utf8"));
		const m = /^(@[^/]+)\//.exec(name ?? "");
		if (m) scopes.add(m[1]);
	}
	if (scopes.size !== 1) {
		console.error(`error: expected exactly one workspace scope, found: ${[...scopes].join(", ") || "(none)"}`);
		process.exit(1);
	}
	return [...scopes][0];
}

/** Current upstream repo slug, detected from a package.json repository field. */
function detectRepo() {
	for (const dir of PKG_GLOBS) {
		const p = join(REPO_ROOT, "packages", dir, "package.json");
		if (!existsSync(p)) continue;
		const url = JSON.parse(readFileSync(p, "utf8")).repository?.url;
		const m = /github\.com[/:]([^/]+\/[^/.]+)/.exec(url ?? "");
		if (m) return m[1];
	}
	console.error("error: could not detect the current repository slug");
	process.exit(1);
}

function walk(dir, out = []) {
	let entries;
	try {
		entries = readdirSync(dir, { withFileTypes: true });
	} catch {
		return out;
	}
	for (const e of entries) {
		if (SKIP_SEGMENTS.has(e.name)) continue;
		const full = join(dir, e.name);
		const rel = relative(REPO_ROOT, full).split("\\").join("/");
		if (SKIP_PREFIXES.some((p) => rel === p || rel.startsWith(p))) continue;
		if (e.isDirectory()) walk(full, out);
		else if (e.isFile() && TEXT_EXT.test(e.name) && !SKIP_BASENAMES.has(e.name)) out.push(full);
	}
	return out;
}

const oldScope = detectScope();
const newScope = positional[0] ? positional[0].replace(/\/+$/, "") : undefined;
const oldRepo = detectRepo();
const newRepo = repoArg ?? oldRepo;

if (reportOnly || !newScope) {
	console.log(`current scope:    ${oldScope}`);
	console.log(`current repo:     ${oldRepo}`);
	console.log(`workspace pkgs:   ${PKG_GLOBS.length}`);
	if (reportOnly) {
		const files = RENAME_ROOTS.flatMap((r) => walk(join(REPO_ROOT, r)));
		let hits = 0;
		let withHits = 0;
		for (const f of files) {
			const n = readFileSync(f, "utf8").split(`${oldScope}/`).length - 1;
			if (n > 0) {
				hits += n;
				withHits++;
			}
		}
		console.log(`files in scope:   ${files.length}`);
		console.log(`files with hits:  ${withHits}`);
		console.log(`occurrences:      ${hits}`);
	}
	if (!newScope) {
		console.log("\nusage: node scripts/fork-rename-scope.mjs @<scope> [--repo owner/name] [--dry-run]");
		process.exit(reportOnly ? 0 : 1);
	}
	console.log("");
}

if (newScope === oldScope && newRepo === oldRepo) {
	console.log(`nothing to do — already at ${newScope} / ${newRepo}`);
	process.exit(0);
}
if (newScope && !newScope.startsWith("@")) {
	console.error(`error: scope must look like @account, got "${newScope}"`);
	process.exit(2);
}

// ---------------------------------------------------------------------------
// 1. Text rewrite
// ---------------------------------------------------------------------------

const files = RENAME_ROOTS.flatMap((r) => walk(join(REPO_ROOT, r)));
let changedFiles = 0;
let changedHits = 0;

for (const file of files) {
	const before = readFileSync(file, "utf8");
	let after = before.split(`${oldScope}/`).join(`${newScope}/`);
	if (newRepo !== oldRepo) {
		after = after.split(`github.com/${oldRepo}`).join(`github.com/${newRepo}`);
		after = after.split(`raw.githubusercontent.com/${oldRepo}`).join(`raw.githubusercontent.com/${newRepo}`);
	}
	if (after === before) continue;
	const hits = before.split(`${oldScope}/`).length - 1;
	changedFiles++;
	changedHits += hits;
	console.log(`  ${relative(REPO_ROOT, file)}  (${hits})`);
	if (!dryRun) writeFileSync(file, after);
}

// ---------------------------------------------------------------------------
// 2. package.json identity fields (scope, repo links, and pi.image are already
//    covered by the text rewrite — this only handles author/contributors)
// ---------------------------------------------------------------------------

let metadataFiles = 0;
if (!noMetadata) {
	const owner = newScope ? newScope.slice(1) : undefined;
	const upstreamOwner = oldScope.slice(1);
	for (const dir of PKG_GLOBS) {
		const path = join(REPO_ROOT, "packages", dir, "package.json");
		if (!existsSync(path)) continue;
		const pkg = JSON.parse(readFileSync(path, "utf8"));
		let touched = false;

		if (owner && pkg.author !== owner) {
			pkg.author = owner;
			touched = true;
		}
		// Upstream authorship must survive into the published metadata, not only
		// into LICENSE — npm shows `author` and users read it as provenance.
		const credit = `${upstreamOwner} <https://github.com/${upstreamOwner}>`;
		const contributors = Array.isArray(pkg.contributors) ? pkg.contributors : [];
		if (!contributors.some((c) => String(c).includes(upstreamOwner))) {
			pkg.contributors = [...contributors, credit];
			touched = true;
		}
		if (!touched) continue;
		metadataFiles++;
		console.log(`  packages/${dir}/package.json  (author/contributors)`);
		if (!dryRun) writeFileSync(path, `${JSON.stringify(pkg, null, "\t")}\n`);
	}
}

console.log(
	`\n${dryRun ? "[dry-run] would change" : "changed"} ${changedFiles} files (${changedHits} scope refs)` +
		`${noMetadata ? "" : ` + ${metadataFiles} package.json metadata`}`,
);
if (!dryRun) {
	console.log("\nNext: npm install   # relink workspace symlinks under the new scope");
	console.log("      npm run check && npm test");
}
